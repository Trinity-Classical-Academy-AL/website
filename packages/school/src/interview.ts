export const CHILD_FIELDS = [
	{ key: 'name', label: 'Child Name', type: 'text' },
	{ key: 'dateOfBirth', label: 'Date of Birth', type: 'date' },
	{ key: 'currentGrade', label: 'Current Grade', type: 'text' },
	{ key: 'school', label: 'School Currently Attending', type: 'text' },
	{ key: 'description', label: 'Describe this child (include any strengths, special needs, etc.)', type: 'textarea' },
] as const;

export type InterviewChild = { name: string; dateOfBirth: string; currentGrade: string; school: string; description: string };
export type InterviewDetails = { firstName: string; lastName: string; year: string; children: InterviewChild[]; answers: Record<string, string> };

export function inquiryDetailsText(details: InterviewDetails | Record<string, never>): string {
	if (!details.firstName) return '';
	return [
		`First Name: ${details.firstName}`, `Last Name: ${details.lastName}`, `Enrollment year: ${details.year}`,
		...details.children.flatMap((child, index) => [`Child ${index + 1}`, ...CHILD_FIELDS.map((field) => `${field.label}: ${child[field.key] || '—'}`)]),
		...INTERVIEW_ANSWERS.map((field) => `${field.label}: ${details.answers[field.key] || '—'}`),
	].join('\n');
}

export function interviewInput(form: FormData) {
	const value = (key: string, max = 2000) => String(form.get(key) ?? '').trim().slice(0, max);
	const firstName = value('firstName', 80);
	const lastName = value('lastName', 80);
	const email = value('email', 254);
	const phone = value('phone', 40);
	const year = value('year', 40);
	const children: InterviewChild[] = [];
	for (let index = 0; index < 20; index += 1) {
		const child = Object.fromEntries(CHILD_FIELDS.map((field) => [field.key, value(`child.${index}.${field.key}`, field.type === 'textarea' ? 2000 : 160)])) as InterviewChild;
		if (Object.values(child).some(Boolean)) children.push(child);
	}
	if (!firstName || !lastName || !email || !phone || !year || !children.length || children.some((child) => !child.name)) {
		return { ok: false as const, error: 'Add your first and last name, email, phone, enrollment year, and a name for each child.' };
	}
	if (!/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(email)) return { ok: false as const, error: 'Enter an email address like name@example.com.' };
	const answers = Object.fromEntries(INTERVIEW_ANSWERS.map((field) => [field.key, value(`answer.${field.key}`)]));
	const details: InterviewDetails = { firstName, lastName, year, children, answers };
	const grades = [...new Set(children.map((child) => {
		const grade = child.currentGrade.trim().toLowerCase();
		if (/^(k|kindergarten|kindergarden)$/.test(grade)) return 'K';
		return /^(?:grade\s*)?([1-8])(?:st|nd|rd|th)?(?:\s*grade)?$/.exec(grade)?.[1] || '';
	}).filter(Boolean))];
	return { ok: true as const, input: { name: `${firstName} ${lastName}`, email, phone, grades, message: '', source: 'interview', notify: true, details } };
}
