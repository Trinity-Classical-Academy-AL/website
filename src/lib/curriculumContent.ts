const MAX_TITLE_LENGTH = 120;
const MAX_BODY_LENGTH = 60000;

const escapeHtml = (value: string) =>
	value
		.replace(/&/g, '&amp;')
		.replace(/</g, '&lt;')
		.replace(/>/g, '&gt;')
		.replace(/"/g, '&quot;')
		.replace(/'/g, '&#39;');

const escapeAttribute = (value: string) => escapeHtml(value).replace(/`/g, '&#96;');

const isSafeHref = (href: string) =>
	href.startsWith('/') ||
	href.startsWith('#') ||
	href.startsWith('https://') ||
	href.startsWith('http://') ||
	href.startsWith('mailto:');

const renderInlineMarkdown = (value: string): string => {
	const links: string[] = [];
	const withLinkTokens = value.replace(/\[([^\]\n]+)\]\(([^)\s]+)\)/g, (_, label, href) => {
		if (!isSafeHref(href)) {
			return `${label} (${href})`;
		}

		const token = `\u0000LINK${links.length}\u0000`;
		links.push(
			`<a href="${escapeAttribute(href)}" rel="noopener noreferrer">${renderInlineMarkdown(label)}</a>`,
		);
		return token;
	});

	const escaped = escapeHtml(withLinkTokens)
		.replace(/\*\*([^*]+)\*\*/g, '<strong>$1</strong>')
		.replace(/\*([^*]+)\*/g, '<em>$1</em>');

	return escaped.replace(/\u0000LINK(\d+)\u0000/g, (_, index) => links[Number(index)] ?? '');
};

const renderParagraph = (lines: string[]) =>
	`<p>${renderInlineMarkdown(lines.join(' ').trim())}</p>`;

export const renderCurriculumMarkdown = (markdown: string) => {
	const html: string[] = [];
	const paragraph: string[] = [];
	let list: string[] = [];

	const flushParagraph = () => {
		if (paragraph.length === 0) return;
		html.push(renderParagraph(paragraph));
		paragraph.length = 0;
	};

	const flushList = () => {
		if (list.length === 0) return;
		html.push(`<ul>${list.map((item) => `<li>${renderInlineMarkdown(item)}</li>`).join('')}</ul>`);
		list = [];
	};

	for (const rawLine of markdown.replace(/\r\n?/g, '\n').split('\n')) {
		const line = rawLine.trim();

		if (line === '') {
			flushParagraph();
			flushList();
			continue;
		}

		const heading = line.match(/^(#{2,4})\s+(.+)$/);
		if (heading) {
			flushParagraph();
			flushList();
			const level = heading[1].length;
			html.push(`<h${level}>${renderInlineMarkdown(heading[2])}</h${level}>`);
			continue;
		}

		const bullet = line.match(/^[-*]\s+(.+)$/);
		if (bullet) {
			flushParagraph();
			list.push(bullet[1]);
			continue;
		}

		flushList();
		paragraph.push(line);
	}

	flushParagraph();
	flushList();

	return html.join('');
};

export const validateCurriculumContent = (input: unknown) => {
	if (!input || typeof input !== 'object') {
		return { ok: false as const, error: 'Curriculum content must be an object.' };
	}

	const candidate = input as { title?: unknown; bodyMarkdown?: unknown };
	const title = typeof candidate.title === 'string' ? candidate.title.trim() : '';
	const bodyMarkdown =
		typeof candidate.bodyMarkdown === 'string' ? candidate.bodyMarkdown.trim() : '';

	if (!title) {
		return { ok: false as const, error: 'Title is required.' };
	}

	if (title.length > MAX_TITLE_LENGTH) {
		return { ok: false as const, error: `Title must be ${MAX_TITLE_LENGTH} characters or fewer.` };
	}

	if (!bodyMarkdown) {
		return { ok: false as const, error: 'Body is required.' };
	}

	if (bodyMarkdown.length > MAX_BODY_LENGTH) {
		return { ok: false as const, error: `Body must be ${MAX_BODY_LENGTH} characters or fewer.` };
	}

	return {
		ok: true as const,
		value: {
			title,
			bodyMarkdown,
		},
	};
};
